import { createHash } from "node:crypto";
import type { Pool, PoolClient } from "pg";

/**
 * Audit-event hash chain (Data Model §7, Threat Model T-02/T-06).
 *
 * Every audit event stores:
 *  - `previous_hash`: the `event_hash` of the previous event in the same
 *    organization (NULL for the first event in the organization).
 *  - `event_hash`: SHA-256 of the canonical JSON of the event's content,
 *    including `previous_hash`. Tampering with any field (or deleting an
 *    event and re-linking) breaks the chain, and `verifyAuditChain` finds it.
 *
 * Two layers protect the log:
 *  1. Database: migration 0008 adds BEFORE UPDATE/DELETE triggers that raise
 *     on any attempt to change or remove an audit_events row.
 *  2. Hash chain: even a writer with direct database access who inserts a
 *     forged event cannot make it link correctly without knowing the exact
 *     canonical form — and any forgery is detected by verification.
 *
 * Notes and limits (be honest about them):
 *  - The chain is per organization. `seq` (migration 0008, an identity
 *    column) gives the strict insertion order used for verification.
 *  - `recordAuditEvent` takes a per-organization advisory lock inside the
 *    caller's transaction, so two concurrent inserts for one organization
 *    cannot compute the same `previous_hash`. The lock key is a 64-bit hash
 *    of the organization UUID; collisions are possible in principle (64-bit
 *    space) and would only serialize two unrelated organizations.
 *  - The payload is stored as jsonb. Verification re-canonicalizes the
 *    parsed payload, so payload values must survive a jsonb round-trip
 *    unchanged (no numbers beyond 2^53, no non-JSON values). Callers must
 *    pass plain JSON data (strings, numbers, booleans, null, arrays,
 *    objects) — enforced by the JsonValue type below.
 *  - `created_at` is generated by the application (not `now()` in the DB)
 *    and passed explicitly, because the hash covers it.
 */

export type JsonValue =
  string | number | boolean | null | JsonValue[] | { [key: string]: JsonValue };

export type JsonObject = { [key: string]: JsonValue };

export interface AuditEventInput {
  organizationId: string;
  /** Null = system-generated event. */
  actorId: string | null;
  eventType: string;
  targetType: string | null;
  targetId: string | null;
  payload: JsonObject;
  modelVersion: string | null;
  /** Generated by the caller (new Date()) and stored verbatim; part of the hash. */
  createdAt: Date;
}

export interface AuditEventRecord {
  id: string;
  organizationId: string;
  actorId: string | null;
  eventType: string;
  targetType: string | null;
  targetId: string | null;
  payload: JsonObject;
  modelVersion: string | null;
  createdAt: Date;
  previousHash: string | null;
  eventHash: string;
  seq: string;
}

/** Canonical JSON: object keys sorted recursively, no whitespace. */
export function canonicalJson(value: unknown): string {
  if (value === null || typeof value !== "object") {
    return JSON.stringify(value) ?? "null";
  }
  if (Array.isArray(value)) {
    return `[${value.map((item) => canonicalJson(item)).join(",")}]`;
  }
  const record = value as Record<string, unknown>;
  const keys = Object.keys(record).sort();
  const parts = keys.map((key) => `${JSON.stringify(key)}:${canonicalJson(record[key])}`);
  return `{${parts.join(",")}}`;
}

interface HashableEvent {
  previous_hash: string | null;
  organization_id: string;
  actor_id: string | null;
  event_type: string;
  target_type: string | null;
  target_id: string | null;
  created_at: string;
  payload: JsonObject;
}

/** The exact content hashed for an event. Kept in one place so the writer and the verifier agree. */
export function hashableEvent(input: AuditEventInput, previousHash: string | null): HashableEvent {
  return {
    previous_hash: previousHash,
    organization_id: input.organizationId,
    actor_id: input.actorId,
    event_type: input.eventType,
    target_type: input.targetType,
    target_id: input.targetId,
    created_at: input.createdAt.toISOString(),
    payload: input.payload,
  };
}

export function computeEventHash(input: AuditEventInput, previousHash: string | null): string {
  return createHash("sha256")
    .update(canonicalJson(hashableEvent(input, previousHash)))
    .digest("hex");
}

function rowToRecord(row: {
  id: string;
  organization_id: string;
  actor_id: string | null;
  event_type: string;
  target_type: string | null;
  target_id: string | null;
  payload: JsonObject;
  model_version: string | null;
  created_at: Date;
  previous_hash: string | null;
  event_hash: string;
  seq: string;
}): AuditEventRecord {
  return {
    id: row.id,
    organizationId: row.organization_id,
    actorId: row.actor_id,
    eventType: row.event_type,
    targetType: row.target_type,
    targetId: row.target_id,
    payload: row.payload,
    modelVersion: row.model_version,
    createdAt: row.created_at,
    previousHash: row.previous_hash,
    eventHash: row.event_hash,
    seq: row.seq,
  };
}

const SELECT_COLUMNS = `
  id, organization_id, actor_id, event_type, target_type, target_id,
  payload, model_version, created_at, previous_hash, event_hash, seq
`;

/**
 * Append one audit event. MUST be called inside a transaction on `client`
 * (the advisory lock is transaction-scoped, and the event must commit or
 * roll back together with the write it records).
 */
export async function recordAuditEvent(
  client: PoolClient,
  input: AuditEventInput,
): Promise<AuditEventRecord> {
  // Serialize appends per organization within this transaction.
  await client.query(
    "SELECT pg_advisory_xact_lock(('x' || substr(md5($1), 1, 16))::bit(64)::bigint)",
    [input.organizationId],
  );
  const latest = await client.query<{ event_hash: string }>(
    "SELECT event_hash FROM audit_events WHERE organization_id = $1 ORDER BY seq DESC LIMIT 1",
    [input.organizationId],
  );
  const previousHash = latest.rows.length > 0 ? latest.rows[0].event_hash : null;
  const eventHash = computeEventHash(input, previousHash);
  const inserted = await client.query(
    `INSERT INTO audit_events
       (organization_id, actor_id, event_type, target_type, target_id, payload,
        model_version, created_at, previous_hash, event_hash)
     VALUES ($1, $2, $3, $4, $5, $6::jsonb, $7, $8, $9, $10)
     RETURNING ${SELECT_COLUMNS}`,
    [
      input.organizationId,
      input.actorId,
      input.eventType,
      input.targetType,
      input.targetId,
      canonicalJson(input.payload),
      input.modelVersion,
      input.createdAt.toISOString(),
      previousHash,
      eventHash,
    ],
  );
  return rowToRecord(inserted.rows[0]);
}

export interface ChainBreak {
  eventId: string;
  organizationId: string;
  seq: string;
  reason: string;
}

export interface ChainVerification {
  ok: boolean;
  totalEvents: number;
  organizations: number;
  /** First broken event, if any. */
  brokenAt: ChainBreak | null;
}

/**
 * Recompute the whole chain from the database and report the first break.
 * Checks, per organization in seq order: (a) previous_hash equals the
 * previous event's event_hash (NULL for the first event), and (b) event_hash
 * equals the recomputed hash of the stored content.
 */
export async function verifyAuditChain(pool: Pool): Promise<ChainVerification> {
  const { rows } = await pool.query(
    `SELECT ${SELECT_COLUMNS} FROM audit_events ORDER BY organization_id, seq`,
  );
  const records = rows.map(rowToRecord);
  const organizations = new Set(records.map((r) => r.organizationId));
  const previousHashByOrg = new Map<string, string | null>();
  for (const record of records) {
    const expectedPrevious = previousHashByOrg.get(record.organizationId) ?? null;
    if (record.previousHash !== expectedPrevious) {
      return {
        ok: false,
        totalEvents: records.length,
        organizations: organizations.size,
        brokenAt: {
          eventId: record.id,
          organizationId: record.organizationId,
          seq: record.seq,
          reason:
            expectedPrevious === null
              ? `expected previous_hash NULL (first event in organization) but found ${record.previousHash}`
              : `expected previous_hash ${expectedPrevious} but found ${record.previousHash}`,
        },
      };
    }
    const recomputed = computeEventHash(
      {
        organizationId: record.organizationId,
        actorId: record.actorId,
        eventType: record.eventType,
        targetType: record.targetType,
        targetId: record.targetId,
        payload: record.payload,
        modelVersion: record.modelVersion,
        createdAt: record.createdAt,
      },
      record.previousHash,
    );
    if (recomputed !== record.eventHash) {
      return {
        ok: false,
        totalEvents: records.length,
        organizations: organizations.size,
        brokenAt: {
          eventId: record.id,
          organizationId: record.organizationId,
          seq: record.seq,
          reason: `stored event_hash ${record.eventHash} does not match recomputed hash ${recomputed} — content was altered`,
        },
      };
    }
    previousHashByOrg.set(record.organizationId, record.eventHash);
  }
  return {
    ok: true,
    totalEvents: records.length,
    organizations: organizations.size,
    brokenAt: null,
  };
}
